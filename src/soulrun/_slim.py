"""The slim engine program (docs/guide/01-design.md): the engine's own texts, handed out by engine node.

``engine_node.aisop.json`` is generated by ``tools/build_engine_node.py`` from the bundled engine's
program files - every text in it is the engine's text, verbatim; only the arrangement by engine node is
SoulRun's, in its ``soulrun_delivery`` groups. This module composes the groups a moment needs into the usual
two AISOP parts, role "system" and role "user".

A turn starts with what its first step and its first engine reply need: the group "entry", and "recovery_entry" when the
turn re-enters a run (entry_program). Every other group follows the engine reply that first needs it, once per turn: a
reply that serves a node brings that node's group (node_part, called by SoulRun's command line after an engine command -
_cmd.passthrough). A part that would take the printed output past the engine's print cap is not printed: one line names
it and the command that prints it, and it is not recorded as given. What a turn has been given is recorded beside the
runs (_records.delivered_path); a new turn starts the record again, since a new turn may be a new model session.
part_for hands out any group or piece on request (soulrun --engine-node), for a model that lost one, ran an engine tool
another way, or was given only that line. Sections that are never handed out are listed in
soulrun_delivery.not_delivered with the reason. A turn that carries a note about an interruption gets the same start,
the note followed first. The sub-agent part of the file is a reference for a planned engine change and is never handed
out here.
"""
from __future__ import annotations

import hashlib
import json
from functools import lru_cache
from pathlib import Path

from . import _engine, _records
from .errors import EngineUnavailable, UsageError

FILE = Path(__file__).resolve().with_name("engine_node.aisop.json")
IDENTITY = ("protocol", "axiom_0", "id", "name", "version")
START = ("entry",)
ON_REENTRY = ("recovery_entry",)
PARAM_KEYS = ("cache_dir", "engine_dir", "entry_mode")
NODE_GROUPS = ("Router.match", "Router.cache-setup", "Engine.execute-report", "Engine.final-answer")
ENDED = ("FAILED", "ABANDONED")
HEADER = "[SOULRUN ENGINE NODE: {names}]"
INTRO = ("the part of the engine program this step needs, handed out now; follow it as part of the program this turn "
         "started with")


@lru_cache(maxsize=1)
def document() -> list:
    """The slim program file, after making sure it was built from the engine that is bundled."""
    doc = json.loads(FILE.read_text(encoding="utf-8"))
    recorded = doc[0]["content"]["soulrun_source"]["main.aisop.json"]["sha256"]
    actual = hashlib.sha256(_engine.MAIN_PROGRAM.read_bytes()).hexdigest()
    if recorded != actual:
        raise EngineUnavailable("SLIM_PROGRAM_STALE", "engine_node.aisop.json was built from a different engine program; "
                                "run python tools/build_engine_node.py", field="engine_node.aisop.json",
                                expected=f"main.aisop.json sha256 {actual}")
    return doc


def delivery() -> dict:
    """The groups: name -> {when, system, functions} (plus not_delivered, filled_by_soulrun and the sub-agent reference)."""
    return document()[0]["content"]["soulrun_delivery"]


def groups() -> tuple[str, ...]:
    """The names of the groups that can be handed out, in the file's order."""
    return tuple(name for name, group in delivery().items() if isinstance(group, dict) and "functions" in group
                 and name != "sub_agent")


def start_groups(entry_mode: str | None) -> tuple[str, ...]:
    """The groups a turn starts with."""
    return START + (() if entry_mode in (None, "", "fresh") else ON_REENTRY)


def _parts(names, given: set[str] | frozenset[str] = frozenset()) -> tuple[dict, dict]:
    """The sections and functions of these groups that were not given yet, in the engine's own order and words."""
    system_src, user_src = document()[0]["content"], document()[1]["content"]
    table = delivery()
    sections = {key for name in names for key in table[name]["system"] if f"system:{key}" not in given}
    functions = {fn for name in names for fn in table[name]["functions"] if f"functions:{fn}" not in given}
    system = {key: value for key, value in system_src.items() if key in sections}
    if "params" in system and tuple(system["params"]) != PARAM_KEYS:
        # params stays the engine's text: the only place the main program says what each entry_mode means. The values
        # reach the model in the [EXECUTION CONTEXT] block (cache_dir, entry_mode) and the entry block (engine_dir); a
        # later engine with a parameter those blocks do not carry is refused.
        raise EngineUnavailable("SLIM_PROGRAM_PARAMS", f"the engine's params are now {list(system['params'])}; the slim "
                                "form hands over only cache_dir, entry_mode and engine_dir", field="params",
                                expected=", ".join(PARAM_KEYS))
    return system, {fn: value for fn, value in user_src["functions"].items() if fn in functions}


def _names(system: dict, functions: dict) -> set[str]:
    return {f"system:{key}" for key in system} | {f"functions:{fn}" for fn in functions}


def entry_program(user_message: str, *, cache_dir, entry_mode: str | None) -> str:
    """The slim program a turn starts with: AISOP JSON, the user's words in its ``user_input``."""
    system_src, user_src = document()[0]["content"], document()[1]["content"]
    sections, functions = _parts(start_groups(entry_mode))
    system = {key: system_src[key] for key in IDENTITY} | sections
    user = {"instruction": user_src["instruction"],
            "user_input": str(user_message),                   # a JSON string value: the words cannot become structure
            "aisop": {"main": user_src["aisop"]["main"]},
            "functions": functions}
    return json.dumps([{"role": "system", "content": system}, {"role": "user", "content": user}], ensure_ascii=False)


def start_turn(cache_dir, entry_mode: str | None, *, turn: dict | None = None) -> bool:
    """Record that a turn of this run starts with the slim program: what entry_program handed out, and which turn it is
    (``turn``: the facts _records.count_turn gave). True when written."""
    sections, functions = _parts(start_groups(entry_mode))
    return _records.write_delivered(cache_dir, _names(sections, functions), turn=turn or {})


def groups_for(reply) -> list[str]:
    """The groups an engine reply calls for. A reply that serves or commits a node carries reply_file; read-only queries
    (an input, a contract, a program contract, a write target) and anything that is not a reply call for none."""
    if not isinstance(reply, dict) or "reply_file" not in reply:
        return []
    wanted = []
    for part in (reply, reply.get("next_plan")):
        if not isinstance(part, dict):
            continue
        node = part.get("node")
        if isinstance(node, dict) and node.get("name"):
            if node["name"] in NODE_GROUPS:
                wanted.append(node["name"])
            elif node.get("kind") == "business":
                wanted.append("business")
        if part.get("dispatch"):
            wanted.append("dispatch")
    state = reply.get("run_state") or (reply.get("run") or {}).get("state")
    if state in ENDED:
        wanted.append("run_failed")
    if reply.get("terminal_delivery_refs"):
        wanted.append("terminal")
    return [name for i, name in enumerate(wanted) if name not in wanted[:i]]


def _render(names, system: dict, functions: dict, intro: str = INTRO) -> str:
    part = []
    if system:
        part.append({"role": "system", "content": system})
    if functions:
        part.append({"role": "user", "content": {"functions": functions}})
    return (HEADER.format(names=", ".join(names)) + " " + intro + "\n```json\n" + json.dumps(part, ensure_ascii=False)
            + "\n```\n")


def node_part(cache_dir, reply, *, room: int | None = None) -> str | None:
    """What an engine reply's step needs and this turn was not given yet, as a short AISOP to print after the reply - or
    None: the turn was not started with the slim program, or nothing is missing. The record is updated. When the part
    does not fit in ``room`` (UTF-8 bytes left under the print cap after the reply), only a line naming it and the
    command that prints it comes back, and nothing is recorded as given."""
    given = _records.read_delivered(cache_dir)
    wanted = groups_for(reply)
    if given is None or not wanted:
        return None
    system, functions = _parts(wanted, given)
    if not system and not functions:
        return None
    new = _names(system, functions)
    table = delivery()
    named = [name for name in wanted
             if any(f"system:{k}" in new for k in table[name]["system"]) or any(f"functions:{f}" in new for f in table[name]["functions"])]
    text = _render(named, system, functions)
    if room is not None and len(text.encode("utf-8")) > room:
        return not_printed(named, cache_dir)
    _records.write_delivered(cache_dir, given | new)
    return text


def not_printed(names, cache_dir) -> str:
    """The line printed in place of a part that would take the output past the print cap."""
    ask = " ".join(f"--engine-node {name}" for name in names)
    return (HEADER.format(names=", ".join(names)) + " this step needs this part of the engine program; it is not printed "
            "here, since with it this output would pass the command line's cap. Before you do this step, run: "
            f"<soulrun> {ask} --cache-dir \"{cache_dir}\"\n")


def part_for(names: list[str], cache_dir=None) -> str:
    """Any group, section or function on request (soulrun --engine-node), whatever the turn was given; with a cache_dir
    of a slim turn, recorded as given."""
    table = delivery()
    known_groups = groups()
    system_src, user_src = document()[0]["content"], document()[1]["content"]
    handed = {key for name in known_groups for key in table[name]["system"]}
    sections, functions = {}, {}
    for name in names:
        if name in known_groups:
            more_system, more_functions = _parts([name])
            sections |= more_system
            functions |= more_functions
        elif name in handed:
            sections[name] = system_src[name]
        elif name in user_src["functions"] and not name.startswith("sub_agent_"):
            functions[name] = user_src["functions"][name]
        else:
            raise UsageError("ENGINE_NODE_UNKNOWN", f"no group, section or function named {name!r} is handed out",
                             field="engine_node", expected=", ".join(known_groups))
    system = {key: value for key, value in system_src.items() if key in sections}
    functions = {fn: value for fn, value in user_src["functions"].items() if fn in functions}
    if cache_dir is not None:
        given = _records.read_delivered(cache_dir)
        if given is not None:
            _records.write_delivered(cache_dir, given | _names(system, functions))
    return _render(names, system, functions, "the part of the engine program asked for; follow it as part of the "
                                             "program this turn started with")


def sizes(entry_mode: str | None = "fresh") -> dict:
    """How much of the main program the slim form hands out (characters, compact JSON): the whole program, what a turn
    starts with, and everything handed out later at most (each piece once)."""
    full = json.dumps(json.loads(_engine.main_program_text()), ensure_ascii=False)
    start = entry_program("x", cache_dir="x", entry_mode=entry_mode)
    started = start_groups(entry_mode)
    later_system, later_functions = _parts([g for g in groups() if g not in started], _names(*_parts(started)))
    later = json.dumps([later_system, later_functions], ensure_ascii=False)
    return {"full": len(full), "slim": len(start), "later": len(later)}
