RECOVERY_PHASES = ("plan", "start", "complete", "cancel", "delivered")


@dataclass(frozen=True)
class RecoveryRequest:
    """What a host tells the engine when the connection to the model broke (the fields SoulBot's runner sends).

    ``phase``: "plan" (the turn failed: what now?), "start" (the wait is over: re-enter), "complete" (the
    re-entered turn ended), "cancel" (the human or the host cancelled it), "delivered" (the question the decision
    asked the host to show was shown). ``recovery_token`` comes from the "plan" decision and goes with the later phases.
    """
    phase: Literal["plan", "start", "complete", "cancel", "delivered"]
    session_id: str
    error_code: str
    invocation_id: str = ""
    error_message: str = ""
    error_details: Mapping[str, Any] = field(default_factory=dict)
    recovery_token: str | None = None
    cancel_reason: str | None = None


def _recovery_request(request):
    if isinstance(request, Mapping):
        try:
            request = RecoveryRequest(**request)
        except TypeError as exc:
            raise UsageError("RECOVERY_REQUEST_INVALID", str(exc), field="request",
                             expected="phase, session_id and error_code; see soulrun.host.RecoveryRequest") from None
    phase, session_id = getattr(request, "phase", None), getattr(request, "session_id", None)
    if phase not in RECOVERY_PHASES:
        raise UsageError("RECOVERY_REQUEST_INVALID", f"phase {phase!r}", field="phase", expected=" | ".join(RECOVERY_PHASES))
    if not isinstance(session_id, str) or not session_id:
        raise UsageError("RECOVERY_REQUEST_INVALID", f"session_id {session_id!r}", field="session_id",
                         expected="the conversation's session_id")
    return request


@_engine_errors
def runner_recovery(request, *, soulrun_cache_dir: PathArg | None = None, agent_dir: PathArg | None = None, resume_mode: bool | None = None) -> dict:
    """The engine's decision after the connection to the model broke.

    ``request`` is a ``RecoveryRequest`` (or a mapping of its fields, or any object with them). The decision's
    ``action`` says what the host does: "resume" (wait ``delay_seconds``, then send phase "start" and give the
    model its ``prompt``; send "complete" when that turn ends), "completed" (the run already finished), "stop"
    (give up; show ``public_text`` when there is one), "ask" (the switch is off: a question for the human - show
    ``public_text``, expanded, then send phase "delivered"; the answer comes as an ordinary message), "wait" / "hold"
    (the switch is on: the run waits for the model's service - show ``public_text`` when there is one, and try
    again after ``next_probe_seconds``; None means do not).

    The engine's handler takes one folder and uses it both to find the run and to name its own tools in
    the re-entry text - true inside a SoulBot agent folder, not with SoulRun, where data and program are
    apart. This door gives the handler the run folder and then points the re-entry text at the program.
    Only those two places of the text are touched; the decision itself is the engine's.
    """
    request = _recovery_request(request)
    data = _cache_dir(soulrun_cache_dir, agent_dir)
    decision = _engine.load("checkpoint_recovery").handle_runner_recovery(data, request, resume_mode=resume_mode)
    prompt = decision.get("prompt") or ""
    if prompt and data.resolve() != _engine.ENGINE_DIR.resolve():
        wrong_tool = str(data.resolve() / "python_tools" / "next_node.py")
        right_tool = str(_engine.ENGINE_DIR.resolve() / "python_tools" / "next_node.py")
        lines = [f"engine_dir: {_engine.ENGINE_DIR.resolve()}" if line.startswith("engine_dir: ") else line
                 for line in prompt.split("\n")]
        decision = {**decision, "prompt": "\n".join(lines).replace(wrong_tool, right_tool)}
    return decision


