"""What a host does around a model turn - thin, named doors onto the bundled engine.

Every host does two things around a model turn: before showing the model's reply to the human it puts the
engine's public blocks back in place of their references (``expand_refs``), and after the turn it tells the
engine what was said (``after_turn``). A full host (one with its own windows, a Stop button, reconnects)
also records a Stop, asks after a restart, and hands the engine a broken connection. Those engine functions
are reachable here without the host having to know where the engine lives or how its modules are loaded.

The doors pass straight through to the engine; they do not authenticate a caller. By default reports are
diagnostic observations, not proof of native child identity. A host's entry-point and record-write isolation
must be separately qualified before original-child continuation can ever be enabled.
Where a host has a rule of its own - expanding references,
marking a question's menu as delivered when it is in the reply - the rule is SoulBot's, the reference host.
"""
